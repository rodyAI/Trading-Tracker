import type { RawStockRecord } from "../../../shared/src/types.js";

type SampleSeed = Omit<
  RawStockRecord,
  | "sharesOutstanding"
  | "operatingIncomeLtm"
  | "cashAndEquivalents"
  | "shortTermInvestments"
  | "shortTermBorrowings"
  | "currentPortionLongTermDebt"
  | "longTermDebt"
> & {
  targetMarketCap: number;
  targetEvToEbit: number | null;
  targetOperatingIncomeLtm: number;
  targetNetDebt?: number;
};

const makeSampleRecord = ({
  targetMarketCap,
  targetEvToEbit,
  targetOperatingIncomeLtm,
  targetNetDebt = targetEvToEbit == null ? 0 : targetEvToEbit * targetOperatingIncomeLtm - targetMarketCap,
  currentPrice,
  ...rest
}: SampleSeed): RawStockRecord => {
  const sharesOutstanding = targetMarketCap / Number(currentPrice);
  const positiveNetDebt = Math.max(targetNetDebt, 0);
  const negativeNetDebt = Math.max(-targetNetDebt, 0);

  return {
    ...rest,
    currentPrice,
    sharesOutstanding,
    operatingIncomeLtm: targetOperatingIncomeLtm,
    cashAndEquivalents: negativeNetDebt,
    shortTermInvestments: 0,
    shortTermBorrowings: positiveNetDebt * 0.2,
    currentPortionLongTermDebt: positiveNetDebt * 0.15,
    longTermDebt: positiveNetDebt * 0.65,
  };
};

